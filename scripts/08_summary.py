"""Step 08 - write results_summary.md from the files in results/ ONLY.

Every number is read from a results file and printed next to its source,
so nothing is typed in by hand. Standard library only (no torch/pandas).
Run from the repo root:  python scripts/08_summary.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
OUT = ROOT / "results_summary.md"


def rows(name):
    with open(R / name, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def js(name):
    with open(R / name, encoding="utf-8") as f:
        return json.load(f)


def src(name):
    return f"`results/{name}`"


def pm(row, col):
    """'mean ± sd' from a summary row; sd omitted when empty (single run)."""
    m, s = row.get(f"{col}_mean", ""), row.get(f"{col}_std", "")
    return f"{m} ± {s}" if s not in ("", None) else f"{m}"


def save_config():
    """Copy every UPPER_CASE setting from config.py into results/00_config.json."""
    import sys
    sys.path.insert(0, str(ROOT))
    import config
    cfg = {}
    for k in dir(config):
        if k.isupper():
            v = getattr(config, k)
            if isinstance(v, Path):
                continue
            cfg[k] = sorted(v) if isinstance(v, set) else ({kk: sorted(vv) for kk, vv in v.items()}
                                                           if isinstance(v, dict) and k == "SCENE_KEYWORDS" else v)
    with open(R / "00_config.json", "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=2)
    print(f"[saved] {R / '00_config.json'}")
    return cfg


